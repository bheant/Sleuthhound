// Runs after `next build`, before scripts/headers.mjs. Writes out/sw.js: a
// service worker that keeps the app shell (every page, script, style, font,
// icon and SQLite's WebAssembly) so Sleuthhound opens without a connection.
// /api and /proxy are never cached. Pages are fetched fresh when online and
// served from the cache when not; hashed assets come from the cache first.
// Each build gets its own cache, and the old one is deleted.

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const out = path.join(root, "out");

function files(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? files(p) : [p];
  });
}

const skip = new Set(["_headers", "_redirects", "sw.js", "og.png"]);
const shell = [];
const hash = crypto.createHash("sha256");
for (const file of files(out).sort()) {
  const rel = path.relative(out, file).split(path.sep).join("/");
  if (skip.has(rel) || rel.startsWith("_not-found")) continue;
  hash.update(rel).update(fs.readFileSync(file));
  // Pages are served at their pretty address: companies.html as /companies.
  if (rel === "index.html") shell.push("/");
  else if (rel.endsWith(".html")) shell.push(`/${rel.slice(0, -".html".length)}`);
  else shell.push(`/${rel}`);
}
const version = `sleuthhound-${hash.digest("hex").slice(0, 12)}`;

const sw = `// Generated by scripts/sw.mjs. Don't edit by hand.
const CACHE = ${JSON.stringify(version)};
const SHELL = ${JSON.stringify(shell)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/") || url.pathname.startsWith("/proxy/")) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() =>
        caches.match(url.pathname, { ignoreSearch: true }).then((hit) => hit || caches.match("/")),
      ),
    );
    return;
  }
  event.respondWith(caches.match(request, { ignoreSearch: true }).then((hit) => hit || fetch(request)));
});
`;

fs.writeFileSync(path.join(out, "sw.js"), sw);
console.log(`Wrote out/sw.js: ${shell.length} files in ${version}.`);
