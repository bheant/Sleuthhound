// Runs before dev and build. Copies SQLite's WebAssembly into public/, and
// bundles the drizzle/ migrations into lib/db/migrations.generated.ts so the
// browser can apply them: there's no file system to read them from.

import fs from "node:fs";
import path from "node:path";

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));

fs.copyFileSync(
  path.join(root, "node_modules/sql.js/dist/sql-wasm-browser.wasm"),
  path.join(root, "public/sql-wasm.wasm"),
);

const journal = JSON.parse(fs.readFileSync(path.join(root, "drizzle/meta/_journal.json"), "utf8"));
const migrations = journal.entries.map(({ tag }) => ({
  tag,
  statements: fs
    .readFileSync(path.join(root, "drizzle", `${tag}.sql`), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
}));

const out = `// Generated by scripts/prepare.mjs from drizzle/. Don't edit by hand.\n\nexport const MIGRATIONS: ReadonlyArray<{ tag: string; statements: readonly string[] }> = ${JSON.stringify(migrations, null, 2)};\n`;
const target = path.join(root, "lib/db/migrations.generated.ts");
if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== out) fs.writeFileSync(target, out);
